const err = (m, status = 400) => Object.assign(new Error(m), { status });

const SLUG_RE = /^[a-z][a-z0-9-]{1,39}$/;
/** WordPress reads the theme folder name as its slug, so it has to be one. */
function slugify(input, fallback = 'my-theme') {
  const s = String(input || '').toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40);
  return SLUG_RE.test(s) ? s : fallback;
}
const titleCase = (slug) => slug.split('-').filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
const esc = (s) => String(s).replace(/\*\//g, '* /'); // nothing written here may close a PHP comment

