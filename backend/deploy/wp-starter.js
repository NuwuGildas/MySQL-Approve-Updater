/** A folder we may write a new project into: nothing there, or nothing that matters. */
async function assertEmptyEnough(dir) {
  let entries;
  try { entries = await fsp.readdir(dir); } catch { return; } // does not exist yet: fine
  const real = entries.filter((e) => !['.git', '.DS_Store', 'Thumbs.db', 'desktop.ini'].includes(e));
  if (real.length) throw err(`${dir} already has files in it (${real.slice(0, 4).join(', ')}${real.length > 4 ? ', …' : ''}); choose an empty folder so nothing of yours is overwritten`);
}

/** Best effort: a generated project is more useful as a git repository than as a folder. */
function gitInit(dir) {
  return new Promise((resolve) => {
    execFile('git', ['init', '--initial-branch=main'], { cwd: dir, timeout: 15000 }, (e) => resolve(!e));
  });
}

/**
 * Write a new WordPress project into `dir`.
 *
 * @param {object} o
 * @param {string} o.dir              absolute folder to create the project in (must be empty)
 * @param {string} [o.name]           what to call the site; defaults to the folder name
 * @param {string} [o.themeSlug]      theme folder name; defaults to <name>-theme
 * @param {string} [o.version]        WordPress version to pin, or "latest"
 * @param {string} [o.configFromVault] vault entry holding the WORDPRESS_DB_* settings
 * @param {boolean} [o.git]           run `git init` afterwards (default true)
 * @returns {Promise<{path, name, themeSlug, themeName, files: string[], git: boolean}>}
 */
async function createProject({ dir, name, themeSlug, version = 'latest', configFromVault = null, git = true } = {}) {
  const root = assertLocalRoot(dir, 'folder');
  await assertEmptyEnough(root);

  const siteName = String(name || path.basename(root)).trim().slice(0, 60) || path.basename(root);
  // a name that slugifies to nothing ("???") must not leave "-theme" behind as the folder name
  const fromName = slugify(siteName, '');
  const slug = slugify(themeSlug || (fromName ? `${fromName}-theme` : 'my-theme'), 'my-theme');
  const themeName = titleCase(slug);
  const themeDir = `wp-content/themes/${slug}`;
  const ctx = { siteName, slug, themeName, version, configFromVault };

  const files = {
    'ship.json': shipJson(ctx),
    '.gitignore': GITIGNORE,
    'README.md': readme(ctx),
    [`${themeDir}/style.css`]: themeStyle(ctx),
    [`${themeDir}/functions.php`]: themeFunctions(ctx),
    [`${themeDir}/header.php`]: themeHeader(ctx),
    [`${themeDir}/footer.php`]: themeFooter(ctx),
    [`${themeDir}/index.php`]: themeIndex(ctx),
    // git does not track empty directories, and these two are the point of the project
    'wp-content/plugins/.gitkeep': '',
    'wp-content/mu-plugins/.gitkeep': '',
  };

  await fsp.mkdir(root, { recursive: true });
  for (const [rel, body] of Object.entries(files)) {
    const p = path.join(root, rel);
    await fsp.mkdir(path.dirname(p), { recursive: true });
    await fsp.writeFile(p, body);
  }

  return { path: root, name: siteName, themeSlug: slug, themeName, files: Object.keys(files).sort(), git: git ? await gitInit(root) : false };
}

module.exports = { createProject, slugify, titleCase, assertEmptyEnough, GITIGNORE, shipJson, readme };
