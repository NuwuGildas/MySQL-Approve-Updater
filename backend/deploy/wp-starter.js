'use strict';
/* Starting a WordPress project with nothing to start from.
 *
 * "Connect a repository" assumes a repository. Plenty of WordPress work does not begin with one: you
 * have a server, a domain and an idea. This writes the smallest thing that is nonetheless a real
 * project - a theme that renders, a place for plugins, a ship.json that says how to deploy it, and a
 * .gitignore that already knows what never belongs in the repository - into a folder you choose.
 *
 * What it deliberately does NOT contain is WordPress itself. Core is downloaded and verified at
 * build time (wp.js) and laid under your files on every deploy, so it is never committed, never
 * stale, and updating it is a version bump rather than a merge.
 *
 * The result is an ordinary local-folder repository. Everything after this point - detect, plan,
 * ship, rollback - is the normal path, with no special case for having been generated.
 */

