const readme = ({ siteName, slug, themeName, version, configFromVault }) => `# ${siteName}

A WordPress project. WordPress itself is **not** in this repository: core ${version === 'latest' ? '(latest)' : version} is
downloaded from wordpress.org at build time, checked against the SHA-1 they publish, and laid
underneath these files on every deploy. What lives here is only what is yours.

\`\`\`
wp-content/themes/${slug}/   your theme, ready to edit
wp-content/plugins/          plugins you maintain yourself
wp-content/mu-plugins/       must-use plugins: loaded always, cannot be deactivated
ship.json                    how this project is built and deployed
\`\`\`

## Deploying it

The target was set up alongside this folder, so **Plan** then **Ship** from the Deployments page.
Each deploy assembles a fresh release - verified core, plus these files over the top - and swaps it
in atomically. Rolling back swaps the previous one back.

## Before the first visit

1. Create the database and a user for it. A deploy never creates, migrates or touches one.
2. Put the credentials in the vault entry **${configFromVault || '(name one in ship.json as stack.wordpress.configFromVault)'}**:
   \`\`\`
   WORDPRESS_DB_NAME=…
   WORDPRESS_DB_USER=…
   WORDPRESS_DB_PASSWORD=…
   WORDPRESS_DB_HOST=localhost
   \`\`\`
3. Ship, then open \`/wp-admin/install.php\` once and finish the five-minute install.
4. In **Appearance → Themes**, activate **${themeName}**. WordPress starts on its own bundled theme;
   yours is there waiting.

## Things that work differently here

- **Installing plugins and themes from wp-admin is switched off.** They would be written into a
  release directory that the next deploy replaces, so they would quietly disappear. Add them to
  \`wp-content/plugins/\` and commit them instead. If you would rather have the admin screens back on
  those terms, set \`WORDPRESS_ALLOW_FILE_MODS=true\` in the vault entry.
- **Media uploads are safe.** They live outside the releases and survive every deploy.
- **Updating WordPress is a version bump.** Change \`stack.wordpress.version\` in \`ship.json\` and ship.
`;

const shipJson = ({ siteName, version, configFromVault }) => JSON.stringify({
  version: 1,
  name: slugify(siteName, 'site'),
  stack: {
    type: 'php',
    framework: 'wordpress',
    wordpress: { version: version || 'latest', contentDir: 'wp-content', core: 'download', intoDir: '', configFromVault: configFromVault || null },
  },
  runtime: { kind: 'php-fpm', docroot: '.' },
  shared: { files: [], dirs: ['wp-content/uploads'] },
  health: { path: '/', expectStatus: [200, 399] },
}, null, 2) + '\n';

