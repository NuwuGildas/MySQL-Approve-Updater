'use strict';
/* Provider isolation for the in-app AI assistant.

   The CLI providers (codex, claude) would otherwise inherit the user's OWN agent setup: MCP
   servers, web search, hooks, approval policies, alternate model providers. Every capability that
   setup enables is a tool the model can use without passing through this app's approval cards,
   which are the only sanctioned way for the assistant to affect anything. So each CLI turn runs
   against a Server-Tools-managed home holding a minimal generated config, with the same
   restrictions repeated as command-line overrides (a stale or hand-edited file must not be able to
   re-enable anything) and with the inherited environment stripped of whatever could redirect the
   CLI elsewhere.

   If the installed CLI does not understand the switches all of that rests on, isolation is
   unenforceable and the turn is rejected — never quietly run unprotected. */

const fs = require('fs');
const fsp = fs.promises;
const os = require('os');
const path = require('path');

/* ---------- environment ---------- */

/* Stripped from the child: the provider's own home/config/API-base variables, proxies and TLS
   overrides (a redirected endpoint is a redirected agent) and NODE_OPTIONS (--require injects code
   into a Node-based CLI). PATH, TEMP and the rest of the OS environment stay: the CLI needs them. */
const ENV_STRIP = [
  /^CODEX_/i, /^CLAUDE_/i, /^ANTHROPIC_/i, /^OPENAI_/i, /^AZURE_OPENAI_/i, /^MCP_/i,
  /^XDG_(CONFIG|DATA|STATE|CACHE)_HOME$/i,
  /^(HTTP|HTTPS|ALL|NO)_PROXY$/i, /^NODE_OPTIONS$/i, /^NODE_EXTRA_CA_CERTS$/i,
  /^SSL_CERT_FILE$/i, /^REQUESTS_CA_BUNDLE$/i, /^NPM_CONFIG_/i,
];

// add = variables Server Tools sets deliberately; they go on last so the strip cannot drop them
function sanitizeEnv(base = process.env, add = {}) {
  const out = {};
  for (const [k, v] of Object.entries(base)) if (v !== undefined && !ENV_STRIP.some((re) => re.test(k))) out[k] = v;
  return Object.assign(out, add);
}

/* ---------- generated configs ---------- */

const CODEX_CONFIG_TOML = `# Generated by Server Tools on every turn — edits are overwritten.
# The assistant may only act through Server Tools' approval cards, so the CLI's own
# capabilities are switched off here and again as -c overrides on the command line.
approval_policy = "never"
sandbox_mode = "read-only"

[tools]
web_search = false
view_image = false

# empty table: no MCP servers, whatever the user's own config declares
[mcp_servers]

[shell_environment_policy]
inherit = "none"

[history]
persistence = "none"
`;

/* TOML values are single-quoted (literal strings): the CLI is spawned through a shell and nested
   double quotes do not survive cmd.exe reliably. */
const CODEX_OVERRIDES = [
  "approval_policy='never'",
  "sandbox_mode='read-only'",
  'tools.web_search=false',
  'tools.view_image=false',
  'mcp_servers={}',
  "shell_environment_policy.inherit='none'",
  "history.persistence='none'",
];

/* Every built-in Claude Code tool, plus the whole MCP namespace. Names no longer shipped by the
   installed CLI (MultiEdit, SlashCommand on 2.1.x) stay in the list and only cost a "matches no
   known tool" warning on stderr: denying a tool that may come back is the safe direction. */
const CLAUDE_DENIED_TOOLS = [
  'Bash', 'BashOutput', 'KillShell', 'Read', 'Write', 'Edit', 'MultiEdit', 'NotebookEdit',
  'Glob', 'Grep', 'WebFetch', 'WebSearch', 'Task', 'TodoWrite', 'SlashCommand', 'ExitPlanMode',
  'mcp__*',
];

const CLAUDE_SETTINGS = {
  permissions: { defaultMode: 'default', allow: [], deny: CLAUDE_DENIED_TOOLS, additionalDirectories: [] },
  enableAllProjectMcpServers: false,
  enabledMcpjsonServers: [],
  disableAllHooks: true, // hooks are shell commands: another way round the approval cards
  includeCoAuthoredBy: false,
  cleanupPeriodDays: 0,
};

/* ---------- capability requirements ---------- */

const REQUIREMENTS = {
  codex: {
    homeEnv: 'CODEX_HOME',
    helpArgs: ['exec', '--help'],
    minVersion: '0.20.0',
    flags: ['--sandbox', '--config', '--skip-git-repo-check'],
  },
  claude: {
    homeEnv: 'CLAUDE_CONFIG_DIR',
    helpArgs: ['--help'],
    minVersion: '1.0.0',
    flags: ['--strict-mcp-config', '--mcp-config', '--settings', /--disallowed-?tools/i],
  },
};

const requirements = (provider) => REQUIREMENTS[provider] || null;

function parseVersion(s) {
  const m = /(\d+)\.(\d+)\.(\d+)/.exec(String(s || ''));
  return m ? m[0] : null;
}

function cmpVersion(a, b) {
  const pa = a.split('.').map(Number), pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) { if (pa[i] !== pb[i]) return pa[i] < pb[i] ? -1 : 1; }
  return 0;
}

const flagLabel = (f) => (f instanceof RegExp ? '--disallowed-tools' : f);

/* Decide whether this installed CLI can actually be locked down.
   Help output is preferred (it states what the binary really accepts); when it is missing or
   unreadable we fall back to a minimum version, and an unknown version counts as unenforceable. */
function assessIsolation(provider, { version = '', help = '' } = {}) {
  const req = REQUIREMENTS[provider];
  const ver = parseVersion(version);
  if (!req) return { provider, enforceable: true, version: ver, missing: [], reason: '' };
  const base = { provider, version: ver, missing: [] };
  if (provider === 'claude') base.disallowFlag = /--disallowed-tools/.test(help) ? '--disallowed-tools' : '--disallowedTools';
  if (/(^|\s)--[a-z]/.test(help)) {
    const missing = req.flags.filter((f) => (f instanceof RegExp ? !f.test(help) : !help.includes(f))).map(flagLabel);
    if (missing.length) return { ...base, enforceable: false, missing, reason: `it does not support ${missing.join(', ')}` };
    return { ...base, enforceable: true, reason: '' };
  }
  if (!ver) return { ...base, enforceable: false, missing: req.flags.map(flagLabel), reason: 'its version could not be determined' };
  if (cmpVersion(ver, req.minVersion) < 0) {
    return { ...base, enforceable: false, missing: req.flags.map(flagLabel), reason: `version ${ver} is older than the ${req.minVersion} needed for ${req.flags.map(flagLabel).join(', ')}` };
  }
  return { ...base, enforceable: true, reason: '' };
}

// a normal API error (409): the provider is connected but this turn cannot be run safely
function isolationRejection(spec, assessment) {
  const cmd = (spec && spec.cmd) || assessment.provider;
  const label = (spec && spec.label) || assessment.provider;
  const ver = assessment.version ? ` ${assessment.version}` : '';
  const e = new Error(
    `${label} cannot be isolated: the installed "${cmd}"${ver} cannot be locked down because ${assessment.reason}. ` +
    'Server Tools only runs an AI provider whose own file, command, web and MCP tools can be switched off, ' +
    `so that every action goes through an approval card. Upgrade ${cmd} (or connect the Claude API provider instead) and reconnect.`
  );
  e.status = 409;
  e.isolation = assessment;
  return e;
}

/* ---------- managed home ---------- */

const homeDir = (dataDir, provider) => path.join(dataDir, 'agent-home', provider);

const sourceHome = (provider) => (provider === 'codex'
  ? process.env.CODEX_HOME || path.join(os.homedir(), '.codex')
  : process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude'));

/* Credentials are the one thing worth inheriting: a fresh home would otherwise log the user out of
   a CLI they have already signed into. Copied file by file (never the config), refreshed when the
   real one is newer, and best-effort — a missing file just means the CLI asks for a login. */
async function copyCredential(from, to) {
  try {
    const src = await fsp.stat(from);
    let dst = null;
    try { dst = await fsp.stat(to); } catch {}
    if (!dst || src.mtimeMs > dst.mtimeMs) await fsp.copyFile(from, to);
  } catch {}
}

/* Rewritten on every call on purpose: whatever the user (or an older build of this app) left in the
   managed home must not outlive it. */
async function ensureProviderHome(dataDir, provider) {
  const dir = homeDir(dataDir, provider);
  await fsp.mkdir(dir, { recursive: true });
  if (provider === 'codex') {
    await fsp.writeFile(path.join(dir, 'config.toml'), CODEX_CONFIG_TOML, 'utf8');
    await copyCredential(path.join(sourceHome('codex'), 'auth.json'), path.join(dir, 'auth.json'));
  } else if (provider === 'claude') {
    await fsp.writeFile(path.join(dir, 'settings.json'), JSON.stringify(CLAUDE_SETTINGS, null, 2), 'utf8');
    await fsp.writeFile(path.join(dir, 'mcp-empty.json'), JSON.stringify({ mcpServers: {} }), 'utf8');
    await copyCredential(path.join(sourceHome('claude'), '.credentials.json'), path.join(dir, '.credentials.json'));
  }
  return dir;
}

/* ---------- invocations (pure: no spawning, so they can be asserted) ---------- */

const q = (s) => `"${s}"`; // spawned with shell:true, so paths and glob-ish values need quoting

function buildCodexInvocation({ home, model, lastFile, baseEnv = process.env }) {
  const args = ['exec', '--skip-git-repo-check', '--sandbox', 'read-only'];
  for (const o of CODEX_OVERRIDES) args.push('-c', o);
  if (model) args.push('-m', model);
  args.push('--output-last-message', q(lastFile), '-');
  // cwd is the managed home, not DATA_DIR: none of the app's own data sits under the CLI's nose
  return { cmd: 'codex', args, cwd: home, env: sanitizeEnv(baseEnv, { CODEX_HOME: home }) };
}

function buildClaudeInvocation({ home, args: baseArgs = [], disallowFlag = '--disallowedTools', baseEnv = process.env }) {
  const args = [
    ...baseArgs,
    '--strict-mcp-config', '--mcp-config', q(path.join(home, 'mcp-empty.json')),
    '--settings', q(path.join(home, 'settings.json')),
    disallowFlag, q(CLAUDE_DENIED_TOOLS.join(',')),
  ];
  return { cmd: 'claude', args, cwd: home, env: sanitizeEnv(baseEnv, { CLAUDE_CONFIG_DIR: home }) };
}

module.exports = {
  ENV_STRIP, CODEX_CONFIG_TOML, CODEX_OVERRIDES, CLAUDE_DENIED_TOOLS, CLAUDE_SETTINGS,
  sanitizeEnv, requirements, parseVersion, cmpVersion, assessIsolation, isolationRejection,
  homeDir, ensureProviderHome, buildCodexInvocation, buildClaudeInvocation,
};
